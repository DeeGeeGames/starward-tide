const {chromium}=require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const out=process.env.HORIZON_OUTPUT_DIR || '/tmp/galaxy-command-horizon';
fs.mkdirSync(out,{recursive:true});
(async function(){
	const browser=await chromium.launch({headless:true,args:['--use-angle=swiftshader','--enable-unsafe-swiftshader']});
	const context=await browser.newContext({viewport:{width:1440,height:900}});
	const page=await context.newPage();page.setDefaultTimeout(7000);
	const errors=[],checks=[];page.on('pageerror',e=>errors.push(e.message));
	try{
		await page.addInitScript(function(){
			const pad={id:'Simulated standard controller',index:0,connected:true,mapping:'standard',timestamp:0,axes:[0,0,0,0],buttons:Array.from({length:17},()=>({pressed:false,touched:false,value:0}))};
			window.testPad=pad;window.testPads=[pad];window.testFocused=true;Object.defineProperty(document,'hasFocus',{configurable:true,value:()=>window.testFocused});
			Object.defineProperty(navigator,'getGamepads',{configurable:true,value:()=>{window.testPolls=(window.testPolls||0)+1;return window.testPads;}});
		});
		const polled=async function(){const before=await page.evaluate(()=>window.testPolls||0);await page.waitForFunction(before=>(window.testPolls||0)>before+1,before);};
		const press=async function(index){await page.evaluate(index=>{window.testPad.buttons[index]={pressed:true,touched:true,value:1};},index);await polled();await page.evaluate(index=>{window.testPad.buttons[index]={pressed:false,touched:false,value:0};},index);await polled();};
		const active=function(){return page.evaluate(()=>document.activeElement.id);};
		const walkTo=async function(id){for(let i=0;i<30;i++){if(await active()===id)return;await press(13);}throw new Error('Could not focus '+id+', active '+await active());};
		const check=function(name){checks.push(name);console.log('PASS '+name);};
		const url=new URL(process.env.GAME_URL || 'http://localhost:3000');url.searchParams.set('diagnostics','1');await page.goto(url.href);await page.waitForFunction(()=>window.conquestDiagnostics);await page.evaluate(()=>window.conquestDiagnostics.enable(false));
		await page.locator('#new-game').waitFor({state:'visible'});
		await page.waitForFunction(()=>!document.querySelector('#new-game').disabled);
		await press(0);
		assert.equal(await page.locator('html').getAttribute('data-input'),'gamepad');
		assert.equal(await active(),'new-game');
		await page.screenshot({path:out+'/title-controller.png'});
		check('deliberate claim consumes activation and shows controller focus');
		await press(0);
		assert(await page.locator('#galaxy-settings').isVisible());
		await press(13);await press(15);
		assert.equal(await page.locator('#map-size').inputValue(),'large');
		await press(14);
		assert.equal(await page.locator('#map-size').inputValue(),'medium');
		await walkTo('setup-next');await press(0);
		assert(await page.locator('#opponent-settings').isVisible());
		await press(15);
		assert.equal(await page.locator('#opponent-count').inputValue(),'2');
		await press(14);
		await walkTo('start-conquest');
		await page.screenshot({path:out+'/opposition-controller.png'});
		await press(0);
		await page.waitForFunction(()=>!document.querySelector('#app').hidden);
		check('controller-only setup changes settings and starts exact preview');
		await press(9);assert.equal(await page.locator('#pause').getAttribute('aria-pressed'),'true');
		await press(5);await press(0);
		assert(await page.locator('#planet-panel').isVisible());
		assert.equal(await active(),'open-dispatch');
		await page.screenshot({path:out+'/game-controller-overview.png'});
		await press(2);await walkTo('send-units');await press(0);
		assert(await page.locator('#destination-prompt').isVisible());
		await press(5);await press(0);
		assert(await page.locator('#destination-prompt').isHidden());
		assert.match(await page.locator('#orders-toggle').textContent(),/[1-9]/);
		check('target snapping, controller dispatch, and paused unit reservation');
		await press(2);await press(1);await walkTo('selection-orders');await press(0);
		assert(await page.locator('#orders-drawer').isVisible());
		let cancelled=false;
		for(let i=0;i<25;i++){
			const text=await page.evaluate(()=>document.activeElement.textContent);
			if(text.includes('Cancel launch')){await press(0);cancelled=true;break;}
			await press(13);
		}
		assert(cancelled);assert.match(await page.locator('#orders-toggle').textContent(),/0/);
		await press(1);
		check('Orders and launch cancellation work without pointer input');
		const before=await page.locator('#map-world').getAttribute('style');
		await page.evaluate(()=>{window.testPad.axes[2]=.8;});await page.waitForTimeout(250);await page.evaluate(()=>{window.testPad.axes[2]=0;});await page.waitForTimeout(100);
		assert.notEqual(await page.locator('#map-world').getAttribute('style'),before);
		check('right-stick camera pan');
		await page.evaluate(()=>{window.testPad.buttons[7]={pressed:true,touched:true,value:1};});await page.waitForTimeout(200);await page.evaluate(()=>{window.testPad.buttons[7]={pressed:false,touched:false,value:0};});
		await press(9);assert.equal(await page.locator('#pause').getAttribute('aria-pressed'),'false');
		await page.evaluate(()=>{window.testPads=[];});await page.waitForFunction(()=>document.querySelector('#pause').getAttribute('aria-pressed')==='true');
		assert.equal(await page.locator('#pause').getAttribute('aria-pressed'),'true');
		assert.match(await page.locator('#controller-status').textContent(),/disconnected/);
		await page.evaluate(()=>{window.testPads=[window.testPad];});await polled();await press(9);
		assert.equal(await page.locator('#pause').getAttribute('aria-pressed'),'true');
		await press(9);assert.equal(await page.locator('#pause').getAttribute('aria-pressed'),'false');
		check('disconnect pauses and reconnect requires deliberate resume');
		await page.evaluate(()=>{window.testFocused=false;window.dispatchEvent(new Event('blur'));window.testPad.buttons[9]={pressed:true,touched:true,value:1};});
		await page.waitForTimeout(200);
		assert.equal(await page.locator('#pause').getAttribute('aria-pressed'),'true');
		await page.evaluate(()=>{window.testFocused=true;});await polled();
		assert.equal(await page.locator('#pause').getAttribute('aria-pressed'),'true');
		await page.evaluate(()=>{window.testPad.buttons[9]={pressed:false,touched:false,value:0};});await polled();
		await press(9);assert.equal(await page.locator('#pause').getAttribute('aria-pressed'),'false');
		check('visible focus loss blocks input and held Start cannot resume on return');
		await press(8);await walkTo('restart');await press(0);
		await page.locator('#confirm-dialog').waitFor({state:'visible'});
		assert.equal(await active(),'confirm-cancel');
		await press(1);assert(await page.locator('#confirm-dialog').isHidden());
		check('restart confirmation is controller reachable and Back safely cancels');
		await page.evaluate(async function(){await window.conquestDiagnostics.carrierPreview('capture');});
		if(await page.locator('#field-guide').isVisible())await press(1);
		const worldTarget=async function(name){for(let i=0;i<40;i++){if(await page.evaluate(()=>document.activeElement.dataset.planet)===name)return;await press(5);}throw new Error('Could not target '+name);};
		await worldTarget('Blue carrier');await press(0);
		const docked=Number(await page.locator('#stat-ships').textContent());
		await walkTo('launch-carrier');await press(0);
		assert(Number(await page.locator('#stat-ships').textContent())<docked);
		await walkTo('bombard-planet');await press(0);
		assert(await page.locator('#destination-prompt').isVisible());
		await worldTarget('Vega');await press(0);
		assert.match(await page.locator('#selection-info').textContent(),/Approaching Vega|Bombarding Vega/);
		check('carrier local launch and bombardment are controller reachable');
		await press(1);await worldTarget('Sol');await press(0);await press(2);await walkTo('send-units');await press(0);
		await worldTarget('Blue carrier');await press(9);
		const cursorBefore=await page.locator('#gamepad-cursor').getAttribute('style');
		await page.waitForFunction(before=>document.querySelector('#gamepad-cursor').getAttribute('style')!==before,cursorBefore);
		await press(0);
		assert(await page.locator('#destination-prompt').isHidden());
		check('snapped moving carrier remains targeted through movement and confirmation');
		assert.equal(errors.length,0,errors.join('\n'));
		check('no JavaScript errors');fs.writeFileSync(out+'/controller-checks.json',JSON.stringify({checks,errors},null,2));
	}finally{await page.close();await context.close();await browser.close();console.log('Task browser closed');}
})().catch(e=>{console.error(e);process.exitCode=1;});
